function renderEditor(screen) {
  const editing = state.editing;
  const record = editing.record;
  const card = el("section", { class: "card" });
  card.append(el("button", { type: "button", class: "linkish", text: t("back"), onclick: () => { state.editing = null; render(); } }));
  card.append(el("h1", { text: t("edit") }));
  const form = el("form");
  const error = el("div", { class: "banner" });
  error.hidden = true;
  form.append(error);
  if (editing.type === "sighting") {
    card.append(el("p", { class: "lead", text: `${nameOf(record)} · ${record.species_latin || ""}` }));
    form.append(field(t("where"), siteOptions(record.site_id, "site_id")));
    form.append(field(t("when"), el("input", { name: "observed_on", type: "date", value: record.observed_on || "" })));
    const numbers = el("div", { class: "grid-2" });
    numbers.append(
      field(t("count"), el("input", { name: "count", value: record.count ?? "", inputmode: "numeric" })),
      field(t("depth"), el("input", { name: "depth_m", value: record.depth_m ?? "", inputmode: "decimal" }))
    );
    form.append(numbers);
    form.append(field(t("notes"), el("textarea", { name: "notes", text: record.notes || "" })));
    const photos = el("div", { class: "photos" });
    (record.media || []).forEach((media) => {
      const wrap = el("div");
      wrap.append(el("img", { src: media.content_url, alt: "" }));
      wrap.append(el("button", {
        type: "button",
        class: "btn quiet",
        text: t("delete"),
        onclick: async () => {
          await api(`/media/${media.id}`, { method: "DELETE" });
          toast(t("photoRemoved"));
          await refreshEditing();
        },
      }));
      photos.append(wrap);
    });
    const file = el("input", { type: "file", accept: "image/*", capture: "environment" });
    file.addEventListener("change", async () => {
      const picked = file.files && file.files[0];
      if (!picked) return;
      const body = new FormData();
      body.set("sighting_id", record.id);
      body.set("photo", picked);
      try {
        await api("/media", { method: "POST", body });
        await refreshEditing();
      } catch (err) {
        error.hidden = false;
        error.textContent = err.message;
      }
    });
    form.append(photos, field(t("addPhoto"), file));
  } else {
    form.append(field(t("where"), siteOptions(record.site_id, "site_id")));
    form.append(field(t("when"), el("input", { name: "dive_date", type: "date", value: record.dive_date || "" })));
    form.append(field(t("startTime"), el("input", { name: "start_time", type: "time", value: (record.start_time || "").slice(0, 5) })));
    form.append(field(t("duration"), el("input", { name: "duration_min", value: record.duration_min ?? "", inputmode: "numeric" })));
    form.append(field(t("maxDepth"), el("input", { name: "max_depth_m", value: record.max_depth_m ?? "", inputmode: "decimal" })));
    form.append(field(t("notes"), el("textarea", { name: "notes", text: record.notes || "" })));
  }
  form.append(el("button", { class: "btn primary", type: "submit", text: t("saveChanges") }));
  form.addEventListener("submit", async (event) => {
    event.preventDefault();
    const raw = Object.fromEntries(new FormData(form).entries());
    const payload = {};
    Object.entries(raw).forEach(([key, value]) => {
      if (value === "") return;
      if (["count", "duration_min"].includes(key)) payload[key] = Number(value);
      else if (["depth_m", "max_depth_m"].includes(key)) payload[key] = Number(value);
      else payload[key] = value;
    });
    const path = editing.type === "sighting" ? `/sightings/${record.id}` : `/dives/${record.id}`;
    try {
      await api(path, { method: "PATCH", body: payload });
      toast(t("saved"));
      state.editing = null;
      await showTab("mine");
    } catch (err) {
      if (err.status === 401) return;
      error.hidden = false;
      error.textContent = err.message;
    }
  });
  card.append(form);
  screen.append(card);
}

async function refreshEditing() {
  state.observations = await api("/me/observations");
  if (!state.editing) return;
  const id = state.editing.record.id;
  const list = state.editing.type === "dive" ? state.observations.dives : state.observations.sightings;
  const found = (list || []).find((item) => item.id === id);
  if (!found) state.editing = null;
  else state.editing.record = found;
  render();
}

function renderMap(screen) {
  screen.append(el("h1", { text: t("mapTitle") }), el("p", { class: "lead", text: t("mapLead") }));
  const data = state.mapData || { sites: [], species_count: 0, sighting_count: 0 };
  const stats = el("div", { class: "stats" });
  [
    [data.species_count || 0, t("speciesStat")],
    [(data.sites || []).length, t("sitesStat")],
    [data.sighting_count || 0, t("sightingsStat")],
  ].forEach(([value, label]) => {
    stats.append(el("div", { class: "stat" }, [el("b", { text: String(value) }), el("span", { text: label })]));
  });
  const located = (data.sites || []).filter((site) => site.lat != null && site.lng != null);
  if (!located.length) {
    const empty = el("div", { class: "card empty" });
    empty.append(el("p", { text: t("emptyMap") }), el("button", {
      type: "button",
      class: "btn primary",
      text: t("reportFirst"),
      onclick: () => showTab("report"),
    }));
    screen.append(stats, empty);
    return;
  }
  const layout = el("div", { class: "map-layout" });
  const mapWrap = el("div", { class: "map-wrap" }, [el("div", { id: "map" })]);
  const side = el("div");
  const chips = el("div", { class: "species-list" });
  const seen = new Map();
  (data.sites || []).forEach((site) => {
    (site.species || []).forEach((species) => {
      const prev = seen.get(species.id) || { ...species, count_sum: 0 };
      prev.count_sum += Number(species.count_sum || 0);
      seen.set(species.id, prev);
    });
  });
  seen.forEach((species) => {
    chips.append(el("span", { class: "pill", text: `${nameOf(species)} ×${species.count_sum}` }));
  });
  side.append(chips);
  (data.sites || []).filter((site) => site.lat == null).forEach((site) => {
    side.append(el("p", { class: "hint", text: `${nameOf(site, "site")} — ${t("noCoords")}` }));
  });
  layout.append(mapWrap, side);
  screen.append(stats, layout);
  const token = mapToken;
  requestAnimationFrame(() => {
    if (token !== mapToken || !window.L) return;
    const div = document.getElementById("map");
    if (!div) return;
    mapObj = L.map(div, { scrollWheelZoom: false });
    L.tileLayer("https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png", {
      attribution: "&copy; OpenStreetMap",
    }).addTo(mapObj);
    const bounds = [];
    located.forEach((site) => {
      const marker = L.circleMarker([site.lat, site.lng], {
        radius: 9,
        color: "#06314a",
        weight: 2,
        fillColor: "#ffd166",
        fillOpacity: 0.95,
      });
      const lines = (site.species || []).map((species) => `${escapeHtml(nameOf(species))} ×${species.count_sum}`).join("<br>");
      marker.bindPopup(`<b>${escapeHtml(nameOf(site, "site"))}</b><br>${lines}`);
      marker.addTo(mapObj);
      bounds.push([site.lat, site.lng]);
    });
    if (bounds.length === 1) mapObj.setView(bounds[0], 12);
    else mapObj.fitBounds(bounds, { padding: [28, 28] });
  });
}

function escapeHtml(value) {
  return String(value ?? "").replace(/[&<>"']/g, (char) => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#39;",
  }[char]));
}

