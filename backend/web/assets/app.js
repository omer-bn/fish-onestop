function el(tag, attrs, children) {
  const node = document.createElement(tag);
  Object.entries(attrs || {}).forEach(([key, value]) => {
    if (value == null || value === false) return;
    if (key === "class") node.className = value;
    else if (key === "text") node.textContent = value;
    else if (key.startsWith("on") && typeof value === "function") node.addEventListener(key.slice(2).toLowerCase(), value);
    else node.setAttribute(key, value);
  });
  (children || []).forEach((child) => {
    if (child) node.append(child);
  });
  return node;
}

function field(label, control) {
  return el("label", { class: "field" }, [el("span", { text: label }), control]);
}

function nameOf(obj, kind) {
  const he = kind === "site" ? obj.site_hebrew || obj.hebrew : obj.species_hebrew || obj.hebrew;
  const en = kind === "site" ? obj.site_english || obj.english : obj.species_english || obj.english;
  const latin = obj.species_latin || obj.latin || "";
  if (state.lang === "he") return he || en || latin;
  return en || he || latin;
}

function fmtDate(iso) {
  if (!iso) return "";
  const day = iso.length === 10 ? `${iso}T00:00:00` : iso;
  return new Intl.DateTimeFormat(state.lang === "he" ? "he-IL" : "en-GB", {
    day: "numeric",
    month: "short",
    year: "numeric",
  }).format(new Date(day));
}

function errorText(data) {
  const detail = data && data.detail;
  if (typeof detail === "string") return detail;
  if (Array.isArray(detail)) return detail.map((item) => item.msg || "").filter(Boolean).join(" ");
  return "";
}

async function api(path, opts = {}) {
  const headers = new Headers(opts.headers || {});
  let body = opts.body;
  if (body && !(body instanceof FormData) && typeof body !== "string") {
    headers.set("content-type", "application/json");
    body = JSON.stringify(body);
  }
  let response;
  try {
    response = await fetch(path, {
      method: opts.method || "GET",
      headers,
      body,
      credentials: "same-origin",
    });
  } catch (err) {
    const wrapped = new Error(t("network"));
    wrapped.status = 0;
    throw wrapped;
  }
  const text = await response.text();
  let data = null;
  if (text) {
    try {
      data = JSON.parse(text);
    } catch {
      data = { detail: text };
    }
  }
  if (!response.ok) {
    const wrapped = new Error(errorText(data) || t("network"));
    wrapped.status = response.status;
    wrapped.data = data;
    if (response.status === 401 && !path.startsWith("/auth/")) {
      state.me = null;
      render();
    }
    throw wrapped;
  }
  return data;
}

