async function boot() {
  const params = new URLSearchParams(location.search);
  const code = params.get("auth_error");
  if (code) {
    state.authError = code;
    history.replaceState(null, "", location.pathname + location.hash);
  }
  if ("serviceWorker" in navigator) {
    navigator.serviceWorker.register("/sw.js").catch(() => {});
  }
  applyChrome();
  try {
    const [me, providers] = await Promise.all([
      api("/auth/me").catch((err) => (err.status === 401 ? null : Promise.reject(err))),
      api("/auth/providers").catch(() => ({ password: true, google: false })),
    ]);
    state.providers = providers || state.providers;
    if (!me) {
      render();
      return;
    }
    state.me = me;
    state.sites = (await api("/sites")).items;
    const hash = location.hash.replace("#", "");
    await showTab(hash || "report");
  } catch {
    state.authError = "network";
    render();
  }
}

boot();
