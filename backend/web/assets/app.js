function renderSighting(sighting) {
  const card = el("article", { class: "obs" });
  card.append(photoNode(sighting.media));
  const body = el("div");
  body.append(el("h3", { text: nameOf(sighting) }));
  const bits = [fmtDate(sighting.observed_on), nameOf(sighting, "site")];
  if (sighting.count != null) bits.push(`×${sighting.count}`);
  if (sighting.depth_m != null) bits.push(`${sighting.depth_m} m`);
  body.append(el("p", { text: bits.filter(Boolean).join(" · ") }));
  if (sighting.notes) body.append(el("p", { text: sighting.notes }));
  const actions = el("div", { class: "row-actions" });
  actions.append(
    el("button", { type: "button", class: "btn", text: t("edit"), onclick: () => openEdit("sighting", sighting) }),
    el("button", {
      type: "button",
      class: "btn danger",
      text: t("delete"),
      onclick: () => askDelete(t("deleteSighting"), () => api(`/sightings/${sighting.id}`, { method: "DELETE" })),
    })
  );
  body.append(actions);
  card.append(body);
  return card;
}

function renderMine(screen) {
  screen.append(el("h1", { text: t("mineTitle") }), el("p", { class: "lead", text: t("mineLead") }));
  const dives = state.observations.dives || [];
  const sightings = state.observations.sightings || [];
  if (!dives.length && !sightings.length) {
    const empty = el("div", { class: "card empty" });
    empty.append(el("p", { text: t("emptyMine") }), el("button", {
      type: "button",
      class: "btn primary",
      text: t("reportFirst"),
      onclick: () => showTab("report"),
    }));
    screen.append(empty);
    return;
  }
  const byDive = new Map(dives.map((dive) => [dive.id, { ...dive, items: [] }]));
  const loose = [];
  sightings.forEach((sighting) => {
    if (sighting.dive_id && byDive.has(sighting.dive_id)) byDive.get(sighting.dive_id).items.push(sighting);
    else loose.push(sighting);
  });
  const stack = el("div", { class: "stack" });
  byDive.forEach((dive) => {
    const block = el("section", { class: "dive" });
    const head = el("header");
    head.append(
      el("div", {}, [
        el("h2", { text: nameOf(dive, "site") || t("diveOptional") }),
        el("p", { text: [fmtDate(dive.dive_date), t(dive.method || "scuba")].filter(Boolean).join(" · ") }),
      ])
    );
    const actions = el("div", { class: "row-actions" });
    actions.append(
      el("button", { type: "button", class: "btn", text: t("edit"), onclick: () => openEdit("dive", dive) }),
      el("button", {
        type: "button",
        class: "btn danger",
        text: t("delete"),
        onclick: () => askDelete(t("deleteDive"), () => api(`/dives/${dive.id}`, { method: "DELETE" })),
      })
    );
    block.append(head, actions);
    dive.items.forEach((sighting) => block.append(renderSighting(sighting)));
    stack.append(block);
  });
  if (loose.length) {
    stack.append(el("h2", { text: t("notTied") }));
    loose.forEach((sighting) => stack.append(renderSighting(sighting)));
  }
  screen.append(stack);
}

