function renderAuth(screen) {
  const mode = state.authMode;
  const card = el("section", { class: "card auth" });
  card.append(el("h1", { text: t(mode === "login" ? "loginTitle" : "registerTitle") }));
  card.append(el("p", { class: "lead", text: t("loginLead") }));
  if (state.authError) {
    const key = AUTH_ERRORS[state.authError] || "googleFailed";
    card.append(el("div", { class: "banner", text: t(key) }));
  }
  if (state.providers.google) {
    const link = el("a", { class: "btn google", href: "/auth/google" });
    link.append(googleMark(), el("span", { text: t("google") }));
    card.append(link, el("div", { class: "or", text: t("or") }));
  }
  const form = el("form");
  form.append(field(t("username"), el("input", { name: "username", autocomplete: "username", required: "required", minlength: "3" })));
  if (mode === "register") {
    form.append(field(t("displayName"), el("input", { name: "display_name", autocomplete: "name", maxlength: "80" })));
    const email = el("input", { name: "email", type: "email", autocomplete: "email" });
    form.append(field(t("email"), email), el("p", { class: "hint", text: t("emailHint") }));
  }
  form.append(
    field(
      t("password"),
      el("input", {
        name: "password",
        type: "password",
        required: "required",
        minlength: mode === "register" ? "8" : "1",
        autocomplete: mode === "register" ? "new-password" : "current-password",
      })
    )
  );
  const error = el("div", { class: "banner", hidden: "hidden" });
  form.append(error);
  const submit = el("button", { class: "btn primary", type: "submit", text: t(mode === "login" ? "signIn" : "createAccount") });
  form.append(submit);
  form.addEventListener("submit", async (event) => {
    event.preventDefault();
    error.hidden = true;
    submit.disabled = true;
    const data = Object.fromEntries(new FormData(form).entries());
    try {
      state.me = await api(mode === "login" ? "/auth/login" : "/auth/register", { method: "POST", body: data });
      state.authError = "";
      state.sites = (await api("/sites")).items;
      await showTab("report");
    } catch (err) {
      error.hidden = false;
      error.textContent = err.message;
      submit.disabled = false;
    }
  });
  card.append(form);
  card.append(
    el("button", {
      class: "linkish",
      type: "button",
      text: t(mode === "login" ? "needAccount" : "haveAccount"),
      onclick: () => {
        state.authMode = mode === "login" ? "register" : "login";
        state.authError = "";
        render();
      },
    })
  );
  screen.append(card);
}

function chipRow(values, current, onPick) {
  const row = el("div", { class: "chips" });
  values.forEach((value) => {
    row.append(
      el("button", {
        type: "button",
        class: `chip${current === value ? " on" : ""}`,
        text: t(value),
        onclick: () => onPick(value),
      })
    );
  });
  return row;
}

function siteOptions(selected, name) {
  const select = el("select", name ? { id: "site", name } : { id: "site" });
  select.append(el("option", { value: "", text: t("chooseSite") }));
  state.sites.forEach((site) => {
    const option = el("option", { value: site.id, text: nameOf(site, "site") });
    if (site.id === selected) option.selected = true;
    select.append(option);
  });
  return select;
}

